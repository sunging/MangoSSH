package website.sung.build;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import org.gradle.api.DefaultTask;
import org.gradle.api.file.DirectoryProperty;
import org.gradle.api.provider.Property;
import org.gradle.api.tasks.CacheableTask;
import org.gradle.api.tasks.Input;
import org.gradle.api.tasks.OutputDirectory;
import org.gradle.api.tasks.TaskAction;

/** Generates variant-local resources so a new Git revision does not invalidate Kotlin compilation. */
@CacheableTask
public abstract class GenerateAppBuildInfo extends DefaultTask {
    /** Twelve lowercase commit characters, or empty when the source has no revision metadata. */
    @Input public abstract Property<String> getGitRevision();

    /** Distribution flavor that owns this variant's code and update behavior. */
    @Input public abstract Property<String> getDistribution();

    /** Isolated generated resource root, registered with exactly one Android variant. */
    @OutputDirectory public abstract DirectoryProperty getOutputDirectory();

    /** Writes only validated build identity; no runtime data or machine-specific values enter it. */
    @TaskAction public void generate() throws IOException {
        String revision = getGitRevision().get();
        String distribution = getDistribution().get();
        if (!revision.matches("[0-9a-f]{12}|")) {
            throw new IllegalArgumentException("Build revision must be empty or 12 lowercase hexadecimal characters");
        }
        if (!distribution.equals("github") && !distribution.equals("fdroid")) {
            throw new IllegalArgumentException("Build distribution must be github or fdroid");
        }
        var directory = getOutputDirectory().get().getAsFile().toPath().resolve("values");
        Files.createDirectories(directory);
        // Validation above restricts both values to an XML-safe alphabet. These
        // machine identifiers must remain identical in every application locale.
        Files.writeString(directory.resolve("app_build_info.xml"), """
            <?xml version="1.0" encoding="utf-8"?>
            <!-- Generated by Gradle. Do not edit. -->
            <resources>
                <string name="app_build_revision" translatable="false">%s</string>
                <string name="app_build_distribution" translatable="false">%s</string>
            </resources>
            """.formatted(revision, distribution), StandardCharsets.UTF_8);
    }
}
